def main(argv):
    out = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUT
    try:
        _, tr, ex = generate(ROOT, out)
    except GenError as exc:
        print(f"gen_rollout: {exc}", file=sys.stderr)
        return 1
    print(f"gen_rollout: {L.code} translated {tr}, excluded {ex}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
