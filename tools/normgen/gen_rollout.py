"""Генератор части пакета `rollout-poll` (P/02; ADR-0125 доп. (5) п. 1, своя форма урока): тесты по трассам машины.

Запуск: python3 tools/normgen/gen_rollout.py --lesson 02-installer [<out>]

Источник — `forms/rollout-poll.traces.tsv` (машина `forms/rollout-poll.machine.yaml` — норма; генератор её не
исполняет за модель — решение «Архитектора» 2026-11-05): трасса — шаг 0 `input <JSON>` (с необязательным `const`),
затем внешние события в момент t (`self …`, `status …`, `commit …`, `read_expired …`, `advance`). Ожидание шага —
утверждения через «; ». Тестом становится каждое наблюдаемое утверждение — `state=<polling|passed|refused>` (с отказом —
`did=refuse <код> <слово>` того же шага): события трассы до этого шага подаются в lessonadapter.RolloutPoll (YOURS,
часть stagetests), сравниваются состояние и отказ (forms/README «CALL normalization» rollout-poll). Утверждения о
переменных машины (alive, need, replied, target.*, reads, did, not без refuse) — внутренние, не наблюдение нормализации:
в описи excluded с причиной.

Выход <out>/go/rollouttests/: `traces_test.go` (`TestRolloutPoll_Trace_<трасса>`, подтест на утверждение),
`inventory.tsv`. Судья — test_gen_rollout.py (подставная машина: зелёное; мутанты — красное).
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import lesson  # noqa: E402
from gen_checks import go_str, gofmt  # noqa: E402

L = lesson.CURRENT
DEFAULT_OUT = L.out
GO_MODULE = L.go_module
TRACES = "forms/rollout-poll.traces.tsv"
COLUMNS = ["trace", "step", "t", "event", "expect"]
STATES = ("polling", "passed", "refused")
EVENT = re.compile(r"(self|status|commit|read_expired|advance|wait_expired)(?: .*)?")
INTERNAL = "an internal variable of the machine — not an observation of the CALL normalization"


class GenError(Exception):
    pass


def camel(name):
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[-_]", name) if w)


def read_traces(root=ROOT):
    path = Path(root) / L.rel / TRACES
    if not path.is_file():
        raise GenError(f"no {L.rel}/{TRACES}")
    lines = [ln for ln in path.read_text(encoding="utf-8").split("\n") if ln and not ln.startswith("#")]
    if not lines or lines[0].split("\t") != COLUMNS:
        raise GenError(f"{TRACES}: columns must be {COLUMNS}")
    traces = {}
    for no, line in enumerate(lines[1:], 2):
        cells = line.split("\t")
        if len(cells) != len(COLUMNS):
            raise GenError(f"{TRACES}: row {no}: {len(cells)} cells")
        name, step, t, event, expect = cells
        tr = traces.setdefault(name, {"input": None, "steps": []})
        if step == "0":
            if not event.startswith("input "):
                raise GenError(f"{TRACES}: {name} step 0 — input <JSON>")
            try:
                tr["input"] = json.loads(event[6:])
            except ValueError as exc:
                raise GenError(f"{TRACES}: {name} input: {exc}") from None
            tr["input_text"] = event[6:]
            tr["step0"] = expect
            continue
        if tr["input"] is None or str(len(tr["steps"]) + 1) != step:
            raise GenError(f"{TRACES}: {name} step {step} — steps from 0 (input), consecutive")
        if not EVENT.fullmatch(event):
            raise GenError(f"{TRACES}: {name} step {step}: event {event[:30]!r}")
        try:
            tv = float(t)
        except ValueError:
            raise GenError(f"{TRACES}: {name} step {step}: t {t!r}") from None
        tr["steps"].append({"n": int(step), "t": tv, "t_text": t, "event": event,
                            "asserts": [a.strip() for a in expect.split(";") if a.strip()]})
    return traces


def observable(asserts, where):
    """→ (state | None, (код, слово) | None, [внутренние утверждения])."""
    state, refuse, internal = None, None, []
    for a in asserts:
        if a.startswith("state="):
            state = a[6:]
            if state not in STATES:
                raise GenError(f"{where}: state {state!r}")
        elif m := re.fullmatch(r"did=refuse (\d+) (.+)", a):
            refuse = (int(m[1]), m[2])
        else:
            internal.append(a)
    if state == "refused" and refuse is None:
        raise GenError(f"{where}: state=refused without did=refuse <code> <word>")
    return state, refuse, internal


def build(root=ROOT):
    traces = read_traces(root)
    body = ["// Code generated by tools/normgen/gen_rollout.py from forms/rollout-poll.traces.tsv (kit part rollout-poll);",
            "// DO NOT EDIT.", "", "package rollouttests", "", 'import "testing"', ""]
    inv, total = [], 0
    for name, tr in traces.items():
        checks = []
        state0, _, internal0 = observable([a.strip() for a in tr.get("step0", "").split(";") if a.strip()], f"{name} step 0")
        for a in internal0:
            inv.append((f"{name}/0/{a}", "excluded", INTERNAL))
        if state0 is not None:                         # шаг 0 — до событий: свежий poll
            checks.append(f"\t\t{{step: 0, upto: 0, state: {go_str(state0)}, result: nil}},")
            inv.append((f"{name}/0/state={state0}", "translated", "-"))
            total += 1
        for k, st in enumerate(tr["steps"]):
            state, refuse, internal = observable(st["asserts"], f"{name} step {st['n']}")
            for a in internal:
                inv.append((f"{name}/{st['n']}/{a}", "excluded", INTERNAL))
            if state is None:
                continue
            res = "nil" if state != "refused" else f"&result{{code: {refuse[0]}, word: {go_str(refuse[1])}}}"
            checks.append(f"\t\t{{step: {st['n']}, upto: {k + 1}, state: {go_str(state)}, result: {res}}},")
            inv.append((f"{name}/{st['n']}/state={state}", "translated", "-"))
            total += 1
        events = ",\n".join(f"\t\t{{{st['t_text']}, {go_str(st['event'])}}}" for st in tr["steps"])
        body += [f"// TestRolloutPoll_Trace_{camel(name)} — the trace {name}: {len(checks)} observed states.",
                 f"func TestRolloutPoll_Trace_{camel(name)}(t *testing.T) {{",
                 f"\trunTrace(t, {go_str(name)}, {go_str(tr['input_text'])}, []event{{\n{events},\n\t}}, []observe{{"]
        body += checks + ["\t})", "}", ""]
    if not total:
        raise GenError(f"{TRACES}: no state assertion — an empty projection")
    files = {"go/rollouttests/traces_test.go": gofmt("\n".join(body)),
             "go/rollouttests/engine_test.go": gofmt(ENGINE.replace("normgen/p02/", GO_MODULE + "/"))}
    lines = ["# Inventory of the rollout-poll trace tests (gen_rollout.py): every assertion of the traces — translated or excluded.",
             "assertion\tstatus\treason"] + ["\t".join(r) for r in inv]
    files["go/rollouttests/inventory.tsv"] = "\n".join(lines) + "\n"
    return files, total, len(inv) - total


ENGINE = '''// Code generated by tools/normgen/gen_rollout.py (kit part rollout-poll); DO NOT EDIT.

// Package rollouttests — the traces of forms/rollout-poll.machine.yaml as tests of your poll (lessonadapter.RolloutPoll,
// yours): for each observed state of a trace, the events up to that step go to a fresh poll; its final state and
// refusal are compared. Run: go test ./internal/rollouttests/.
package rollouttests

import (
	"encoding/json"
	"fmt"
	"testing"

	"normgen/p02/lessonadapter"
)

type event struct {
	t     float64
	event string
}

type result struct {
	code int
	word string
}

type observe struct {
	step   int
	upto   int
	state  string
	result *result
}

func runTrace(t *testing.T, name, input string, events []event, checks []observe) {
	t.Helper()
	for _, c := range checks {
		c := c
		t.Run(fmt.Sprintf("step%d", c.step), func(t *testing.T) {
			evs := make([]lessonadapter.Event, 0, c.upto)
			for _, e := range events[:c.upto] {
				evs = append(evs, lessonadapter.Event{T: e.t, Event: e.event})
			}
			var p lessonadapter.Poll
			func() {
				defer func() {
					if r := recover(); r != nil {
						t.Fatalf("%s step %d: RolloutPoll panicked: %v", name, c.step, r)
					}
				}()
				p = lessonadapter.RolloutPoll(json.RawMessage(input), evs)
			}()
			if p.State != c.state {
				t.Fatalf("%s step %d: state %q, want %q", name, c.step, p.State, c.state)
			}
			switch {
			case c.result == nil && p.Result != nil:
				t.Fatalf("%s step %d: result %+v, want none", name, c.step, *p.Result)
			case c.result != nil && p.Result == nil:
				t.Fatalf("%s step %d: no result, want %d %q", name, c.step, c.result.code, c.result.word)
			case c.result != nil && (p.Result.Code != c.result.code || p.Result.Word != c.result.word):
				t.Fatalf("%s step %d: result %d %q, want %d %q", name, c.step, p.Result.Code, p.Result.Word,
					c.result.code, c.result.word)
			}
		})
	}
}
'''


def generate(root=ROOT, out=DEFAULT_OUT):
    files, tr, ex = build(root)
    out = Path(out)
    for rel, text in files.items():
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        (out / rel).write_text(text, encoding="utf-8")
    return out, tr, ex


KIT_DIRS = ("rollouttests",)
JUDGE = HERE / "test_gen_rollout.py"


def kit_files(module, out=DEFAULT_OUT):
    files, _, _ = build(ROOT)
    res = []
    for rel, text in sorted(files.items()):
        kept = Path(out) / rel
        if not kept.is_file() or kept.read_text(encoding="utf-8") != text:
            raise GenError(f"{kept} is stale: run tools/normgen/gen_rollout.py --lesson {L.key}")
        data = kept.read_bytes().replace(f'"{GO_MODULE}/'.encode(), f'"{module}/internal/'.encode())
        res.append(("rollouttests", rel.rsplit("/", 1)[1], data, "generated", str(kept.relative_to(ROOT))))
    return res


def provenance():
    import hashlib

    def entry(path):
        return {"path": str(Path(path).relative_to(ROOT)), "sha256": hashlib.sha256(Path(path).read_bytes()).hexdigest()}
    return {"form": [entry(Path(ROOT) / L.rel / TRACES), entry(Path(ROOT) / L.rel / "forms/rollout-poll.machine.yaml")],
            "generator": entry(Path(__file__).resolve()), "handwritten": [], "judge": entry(JUDGE)}


