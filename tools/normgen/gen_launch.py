def render():
    """→ {путь в out (от go/): текст}."""
    try:
        lesson.require(L, "gen_launch (the frame items, the mark)")
    except lesson.LessonError as exc:
        raise GenError(str(exc)) from None
    for p in (RUNTIME, FRAME, FLAGS, OPENAPI, NORMS):
        if not p.is_file():
            raise GenError(f"no {p}")
    text = RUNTIME.read_text(encoding="utf-8")
    if not re.search(r"^package launch$", text, re.M):
        raise GenError(f"{RUNTIME}: not package launch")
    head = f"// Code generated by tools/normgen/gen_launch.py: copy of tools/normgen/{RUNTIME.relative_to(HERE)}; DO NOT EDIT.\n\n"
    main = MAIN.format(flags_sha=sha(FLAGS), openapi_sha=sha(OPENAPI), openapi_name=OPENAPI.name, module=GO_MODULE)
    frame = FRAME.read_text(encoding="utf-8")
    if frame.count("// @NORMS@\n") != 1:
        raise GenError(f"{FRAME}: no single «// @NORMS@» line")
    frame = (f"// Generated by tools/normgen/gen_launch.py (kit part launch) from tools/normgen/{FRAME.relative_to(HERE)} on\n"
             f"// spec/{NORMS.name} sha256 {sha(NORMS)}.\n\n") + frame.replace("// @NORMS@\n", frame_norms())
    return {"launch/launch.go": gofmt(head + text), "cmd/configstore/main.go": gofmt(main),
            "frame/frame.go": gofmt(frame)}


def frame_norms():
    """Якоря пунктов Н2.1 о рамке (FRAME_ITEMS) с первой строкой текста — для шапки рамки."""
    import gen_core
    sec = gen_core.find(gen_core.sections(NORMS.read_text(encoding="utf-8")), "Н2.1 Request parsing")
    out = [f"// What the strict frame must meet — spec/{NORMS.name} «Н2.1 Request parsing» (and «Implementation",
           "// decides» item 9: the drain volume and time):", "//"]
    for start in FRAME_ITEMS:
        hits = [(a, t) for a, t in sec[2] if t.startswith(start)]
        if len(hits) != 1:
            raise GenError(f"{NORMS.name}: Н2.1 item {start!r} — {len(hits)} found, want 1")
        out.append(f"//   req: {hits[0][0]} — {gen_core.brief(hits[0][1])}")
    return "\n".join(out) + "\n"


def generate(out=DEFAULT_OUT):
    gdir = Path(out) / "go"
    for rel, text in render().items():
        (gdir / rel).parent.mkdir(parents=True, exist_ok=True)
        (gdir / rel).write_text(text, encoding="utf-8")
    return gdir


def kit_files(module, out=DEFAULT_OUT):
    """→ [(каталог в internal, имя, байты, происхождение, источник, своё у реализации)]; GenError — out устарел."""
    files = []
    for rel, text in sorted(render().items()):
        kept = Path(out) / "go" / rel
        if not kept.is_file() or kept.read_text(encoding="utf-8") != text:
            raise GenError(f"{kept} is stale: run tools/normgen/gen_launch.py")
        data = kept.read_bytes().replace(f'"{GO_MODULE}/'.encode(), f'"{module}/internal/'.encode())
        sub, name = rel.rsplit("/", 1)
        own = rel in OWN
        origin = "generated" if own else "handwritten"
        source = kept if own else RUNTIME
        sub = "../cmd/configstore" if rel == "cmd/configstore/main.go" else sub
        files.append((sub, name, data, origin, str(Path(source).relative_to(ROOT)), own))
    return files


def provenance():
    """Паспорт части (ADR-0125 доп. (1) п. 6 (а)): формы, генератор, ручная среда, судья."""
    def entry(path):
        return {"path": str(Path(path).relative_to(ROOT)), "sha256": sha(path)}
    return {"form": [entry(FLAGS), entry(OPENAPI), entry(NORMS)], "generator": entry(Path(__file__).resolve()),
            "handwritten": [entry(RUNTIME), entry(FRAME)], "judge": entry(JUDGE)}


