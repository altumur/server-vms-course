def main(argv):
    out = argv[1] if len(argv) > 1 else DEFAULT_OUT
    try:
        print(generate(out))
    except GenError as exc:
        print(f"gen_launch: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
