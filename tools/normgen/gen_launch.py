"""Generate the store daemon launch frame (ADR-0083 addendum (95), item 3; ADR-0125 generators2+3).

  python3 tools/normgen/gen_launch.py [<out>]
Default: tools/normgen/out/p01-1. Copy launch/go/launch.go to go/launch: parse flags, refuse startup with exit 2, run the no-raft box, maintain FORMAT, inherit LISTEN_FDS/LISTEN_FDNAMES or create flat admin.sock0600 and role.sock0660 sockets, serve App.Frame and handle SIGTERM. NotImplemented responds503.

Copy the temporary net/http frame to frame/frame.go with N2.1 requirement anchors. The implementation owns this file, installed once without overwrite, and must replace it with strict N2.1 parsing. cmd/configstore/main.go is likewise editable and installed once; it calls launch.Main with format marker, coreadapter.Open and frame.New, recording source SHAs.

Requires door, flags and stagetests using the same coreadapter.Open. Until Open replaces ErrNotImplemented, launch.Empty returns absent for Get and503 otherwise, so accept:1.1:01-absent passes on the shipped kit. launch_judge.py runs the P/01.1 runner against that unmodified kit."""
