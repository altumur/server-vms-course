"""Генератор части пакета `launch` (ADR-0083 доп. (95) п. 3; ADR-0125 № 2 и № 3 вместе): каркас демона хранилища.

Запуск: python3 tools/normgen/gen_launch.py [<out>]   (по умолчанию tools/normgen/out/p01-1)

Выход в <out>/go:
- launch/launch.go — копия ручной среды tools/normgen/launch/go/launch.go: разбор флагов пакетом flags (генератор № 3,
  forms/daemon-flags.tsv), отказ запуска кодом 2, сборка без raft (Н1.3 box), метка FORMAT (Н1.3 format), плоские
  сокеты (Н1.3 sockets: унаследованные LISTEN_FDS/LISTEN_FDNAMES, иначе свои admin.sock 0600, <роль>.sock 0660),
  HTTP на каждом сокете через coreadapter.Handle (apidoor.Route → Dispatch → Encode над Core модели), SIGTERM;
  NotImplemented — Core с ответами 503 «not implemented»;
- cmd/configstore/main.go — точка входа: launch.Main с меткой и coreadapter.Open; файл реализации — пакет кладёт его
  один раз и не перетирает (шапка называет sha256 форм, на которых он построен).
Часть требует door (apidoor), flags и stagetests (coreadapter — тот же Open, что у тестов этапов).
Пока coreadapter.Open — заглушка пакета (ErrNotImplemented), каркас отвечает своим пустым ядром launch.Empty
(Get — всегда отсутствующая строка, прочее — 503): этап launch (gate accept:1.1:01-absent) закрыт пакетом как есть.
Судья — раннер P/01.1 на пакете без правок: `launch_judge.py`.
"""
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DEFAULT_OUT = HERE / "out/p01-1"
RUNTIME = HERE / "launch/go/launch.go"
FLAGS = ROOT / "Platform/01-store/forms/daemon-flags.tsv"
OPENAPI = ROOT / "Platform/01-store/spec/01-store.api.openapi.yaml"
JUDGE = HERE / "launch_judge.py"
GO_MODULE = "normgen/p01-1"
KIT_DIRS = ("launch", "../cmd/configstore")


class GenError(Exception):
    pass


def gofmt(src):
    exe = shutil.which("gofmt")
    if not exe:
        raise GenError("gofmt is not in PATH")
    done = subprocess.run([exe], input=src, capture_output=True, text=True)
    if done.returncode:
        raise GenError(f"gofmt rejects generated Go: {done.stderr[:2000]}")
    return done.stdout


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


MAIN = '''// Generated by tools/normgen/gen_launch.py (kit part launch) on forms/daemon-flags.tsv sha256 {flags_sha} and
// spec/01-store.api.openapi.yaml sha256 {openapi_sha}. YOURS from here: the kit puts this file once and never
// overwrites it.

// Command configstore — the store daemon: launch.Main parses the flags of forms/daemon-flags.tsv (a refusal — exit 2),
// checks the FORMAT mark in -dir, opens your core (coreadapter.Open — the same Open as the stage tests; while it is
// the kit's stub, the empty core of the frame answers: every key absent), listens on -sockets (admin.sock and a
// <role>.sock per role of -rights) and serves HTTP through coreadapter.Handle until SIGTERM.
package main

import (
	"os"

	"{module}/coreadapter"
	"{module}/launch"
)

// mark — your on-disk format (P/01.3 Н1.3 format): change Format or Version when your format changes.
var mark = launch.Mark{{Format: "configstore", Version: 1, Impl: "configstore"}}

func main() {{
	os.Exit(launch.Main(os.Args[1:], os.Getenv, launch.App{{
		Mark: mark,
		Open: coreadapter.Open, // yours: internal/coreadapter/open.go (its stub — the empty core of the frame)
		Raft: false,            // a box build: -group-size 3|5, -join, -door — exit 2 «this build has no raft»
	}}))
}}
'''


def render():
    """→ {путь в out (от go/): текст}."""
    for p in (RUNTIME, FLAGS, OPENAPI):
        if not p.is_file():
            raise GenError(f"no {p}")
    text = RUNTIME.read_text(encoding="utf-8")
    if not re.search(r"^package launch$", text, re.M):
        raise GenError(f"{RUNTIME}: not package launch")
    head = f"// Code generated by tools/normgen/gen_launch.py: copy of tools/normgen/{RUNTIME.relative_to(HERE)}; DO NOT EDIT.\n\n"
    main = MAIN.format(flags_sha=sha(FLAGS), openapi_sha=sha(OPENAPI), module=GO_MODULE)
    return {"launch/launch.go": gofmt(head + text), "cmd/configstore/main.go": gofmt(main)}


def generate(out=DEFAULT_OUT):
    gdir = Path(out) / "go"
    for rel, text in render().items():
        (gdir / rel).parent.mkdir(parents=True, exist_ok=True)
        (gdir / rel).write_text(text, encoding="utf-8")
    return gdir


def kit_files(module, out=DEFAULT_OUT):
    """→ [(каталог в internal, имя, байты, происхождение, источник, своё у реализации)]; GenError — out устарел."""
    files = []
    for rel, text in sorted(render().items()):
        kept = Path(out) / "go" / rel
        if not kept.is_file() or kept.read_text(encoding="utf-8") != text:
            raise GenError(f"{kept} is stale: run tools/normgen/gen_launch.py")
        data = kept.read_bytes().replace(f'"{GO_MODULE}/'.encode(), f'"{module}/internal/'.encode())
        sub, name = rel.rsplit("/", 1)
        own = rel == "cmd/configstore/main.go"
        origin = "generated" if own else "handwritten"
        source = kept if own else RUNTIME
        files.append(("../cmd/configstore" if own else sub, name, data, origin, str(Path(source).relative_to(ROOT)), own))
    return files


def provenance():
    """Паспорт части (ADR-0125 доп. (1) п. 6 (а)): формы, генератор, ручная среда, судья."""
    def entry(path):
        return {"path": str(Path(path).relative_to(ROOT)), "sha256": sha(path)}
    return {"form": [entry(FLAGS), entry(OPENAPI)], "generator": entry(Path(__file__).resolve()),
            "handwritten": [entry(RUNTIME)], "judge": entry(JUDGE)}


