"""Machine-only comments for emitted code; producer source is not normalized.

Go strings/runes and raw strings are lexical data. Python removes only COMMENT
tokens and syntactic docstrings, leaving other strings and executable AST intact.
Callers supply actual input identities; package documentation and fixtures are not
code and must never be sent through these functions merely by their suffix.
"""
import ast
import io
import re
import tokenize


class SourceError(ValueError):
    pass


_GO_DIRECTIVE = re.compile(r"//(?:go:|line | \+build\b|export )")
_GO_REQUIREMENT = re.compile(r"//[ \t]*req:[ \t]*(P/[0-9]+\.[0-9]+-R[0-9]+)[ \t]*\Z")
_PY_ENCODING = re.compile(r"#.*?coding[:=][ \t]*[-\w.]+")
_PY_DIRECTIVE = re.compile(r"#[ \t]*(?:type:|noqa\b|fmt:)")


def identity_header(generator, sources, *, language="go", editable=False):
    if language not in {"go", "python"}:
        raise SourceError("unknown emitted code language")
    if not isinstance(generator, str) or not generator or any(ord(c) < 32 for c in generator):
        raise SourceError("invalid generator identity")
    prefix = "//" if language == "go" else "#"
    lines = [] if editable else [f"{prefix} Code generated by {generator}; DO NOT EDIT."]
    seen = {}
    for path, digest in sources:
        if (not isinstance(path, str) or not path or any(ord(c) < 32 or ord(c) == 127 for c in path)
                or not isinstance(digest, str) or re.fullmatch(r"[0-9a-f]{64}", digest) is None):
            raise SourceError("invalid source identity")
        if path in seen:
            if seen[path] != digest:
                raise SourceError("conflicting source identity")
            continue
        seen[path] = digest
        lines += [f"{prefix} Source: {path}", f"{prefix} sha256: {digest}"]
    return "\n".join(lines) + ("\n\n" if lines else "")


def _checked_header(header, prefix):
    waiting_sha, generated = False, False
    for line in header.split("\n"):
        if not line:
            continue
        if re.fullmatch(re.escape(prefix) + r" Code generated by .+; DO NOT EDIT\.", line):
            if generated or waiting_sha:
                raise SourceError("malformed generated identity header")
            generated = True
        elif line.startswith(prefix + " Source: ") and line != prefix + " Source: " and not waiting_sha:
            waiting_sha = True
        elif re.fullmatch(re.escape(prefix) + r" sha256: [0-9a-f]{64}", line) and waiting_sha:
            waiting_sha = False
        else:
            raise SourceError("header contains non-machine text or an incomplete source identity")
    if waiting_sha:
        raise SourceError("source identity header has no SHA256")
    return header


def go_source(text, *, header="", anchor_ids=None):
    if not isinstance(text, str) or not isinstance(header, str):
        raise SourceError("emitted Go source and header must be text")
    result, start, at, size = [], 0, 0, len(text)
    known_anchors = None if anchor_ids is None else frozenset(anchor_ids)
    while at < size:
        char = text[at]
        if char in ('"', "'", "`"):
            quote, opened = char, at
            at += 1
            while at < size:
                if quote != "`" and text[at] == "\\":
                    at += 2
                    continue
                if text[at] == quote:
                    at += 1
                    break
                if quote != "`" and text[at] in "\r\n":
                    raise SourceError("newline in quoted Go literal")
                at += 1
            else:
                raise SourceError(f"unterminated Go literal at {opened}")
            continue
        if text.startswith("//", at):
            end = text.find("\n", at + 2)
            end = size if end == -1 else end
            comment = text[at:end]
            if _GO_DIRECTIVE.match(comment):
                at = end
                continue
            if known_anchors is not None and re.match(r"//[ \t]*req:", comment):
                match = _GO_REQUIREMENT.fullmatch(comment)
                if match is None or match[1] not in known_anchors:
                    raise SourceError("requirement comment is not one exact existing source anchor")
                at = end
                continue
            result += [text[start:at], " "]
            start, at = end, end
            continue
        if text.startswith("/*", at):
            end = text.find("*/", at + 2)
            if end == -1:
                raise SourceError("unterminated Go block comment")
            end += 2
            comment = text[at:end]
            # Cgo preambles are compiler input, not explanatory Go comments.
            if re.search(r"(?m)^[ \t]*#(?:cgo|include|define)\b", comment[2:-2]):
                result += [text[start:at], comment]
            else:
                result += [text[start:at], " " + "".join(c for c in comment if c in "\r\n")]
            start, at = end, end
            continue
        at += 1
    result.append(text[start:])
    return _checked_header(header, "//") + "".join(result)


def _offsets(text):
    parts = text.split("\n")
    rows = [part + "\n" for part in parts[:-1]] + [parts[-1]]
    offsets, total = [], 0
    for row in rows:
        offsets.append(total)
        total += len(row)
    return rows, offsets


def python_source(text, *, header=""):
    if not isinstance(text, str) or not isinstance(header, str):
        raise SourceError("emitted Python source and header must be text")
    try:
        tree = ast.parse(text)
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (SyntaxError, tokenize.TokenError, IndentationError) as exc:
        raise SourceError(f"invalid emitted Python source: {exc}") from exc
    rows, starts = _offsets(text)

    def position(point, *, byte_column=False):
        line, column = point
        if byte_column:
            column = len(rows[line - 1].encode("utf-8")[:column].decode("utf-8"))
        return starts[line - 1] + column

    changes = []
    for node in ast.walk(tree):
        if (isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.body
                and isinstance(node.body[0], ast.Expr) and isinstance(node.body[0].value, ast.Constant)
                and isinstance(node.body[0].value.value, str)):
            expr = node.body[0]
            begin = position((expr.lineno, expr.col_offset), byte_column=True)
            end = position((expr.end_lineno, expr.end_col_offset), byte_column=True)
            lines = text[begin:end].count("\n")
            replacement = "None" if not lines else "(" + "\n" * lines + "None)"
            changes.append((begin, end, replacement))
    insertion_line = 0
    for token in tokens:
        if token.type != tokenize.COMMENT:
            continue
        directive = (_PY_DIRECTIVE.match(token.string) is not None
                     or token.start[0] <= 2 and _PY_ENCODING.match(token.string) is not None
                     or token.start == (1, 0) and token.string.startswith("#!"))
        if directive:
            if token.start[0] <= 2:
                insertion_line = max(insertion_line, token.start[0])
            continue
        begin, end = position(token.start), position(token.end)
        if not any(a <= begin and end <= b for a, b, _ in changes):
            changes.append((begin, end, ""))
    insertion = starts[insertion_line] if insertion_line < len(starts) else len(text)
    changes.append((insertion, insertion, _checked_header(header, "#")))
    result, previous = [], 0
    for begin, end, replacement in sorted(changes):
        if begin < previous:
            raise SourceError("overlapping emitted Python comment/docstring ranges")
        result += [text[previous:begin], replacement]
        previous = end
    result.append(text[previous:])
    return "".join(result)
