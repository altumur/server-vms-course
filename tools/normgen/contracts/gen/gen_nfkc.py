"""The NFKC tables of the package contracts (Unicode 15.0.0, UAX #15) from unicodedata of Python 3.12: the full
compatibility decompositions, the canonical combining classes and the primary composites (the address contract А4
names NFKC by the tables of Unicode 15.0.0). Writes contracts/go/nfkc_tables.go; the judge test_contracts.py checks
that the file is fresh and that NFKC of the package equals unicodedata.normalize("NFKC")."""
import shutil
import subprocess
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "go/nfkc_tables.go"
SB, SC = 0xAC00, 11172


def go_string(s):
    return '"' + "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else f"\\U{ord(c):08X}" for c in s) + '"'


def render():
    assert unicodedata.unidata_version == "15.0.0", unicodedata.unidata_version
    decomp, ccc, comp = [], [], []
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000 or SB <= cp < SB + SC:
            continue
        c = chr(cp)
        if k := unicodedata.combining(c):
            ccc.append((cp, k))
        if (d := unicodedata.normalize("NFKD", c)) != c:
            decomp.append((cp, d))
        raw = unicodedata.decomposition(c)
        if raw and not raw.startswith("<"):
            parts = [int(x, 16) for x in raw.split()]
            if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == c:
                comp.append((parts[0], parts[1], cp))
    w = ["// Code generated by tools/normgen/contracts/gen/gen_nfkc.py from unicodedata 15.0.0; DO NOT EDIT.", "",
         "package contracts", "", "var nfkdTable = map[rune]string{"]
    w += [f"\t0x{cp:X}: {go_string(d)}," for cp, d in decomp]
    w += ["}", "", "var cccTable = map[rune]uint8{"]
    w += [f"\t0x{cp:X}: {k}," for cp, k in ccc]
    w += ["}", "", "var compTable = map[[2]rune]rune{"]
    w += [f"\t{{0x{a:X}, 0x{b:X}}}: 0x{c:X}," for a, b, c in comp]
    w += ["}", ""]
    gofmt = shutil.which("gofmt") or "/opt/go1.22.10/bin/gofmt"
    return subprocess.run([gofmt], input="\n".join(w), capture_output=True, text=True, check=True).stdout


def main():
    OUT.write_text(render(), encoding="utf-8")
    print(OUT, file=sys.stderr)


if __name__ == "__main__":
    main()
